import { useMemo, useState } from "react";
import { useQuery } from "@tanstack/react-query";
import { LayoutDashboard, ClipboardList, Users, BookOpen, Search, ChevronLeft, ChevronRight } from "lucide-react";
import { Layout } from "../../components/Layout";
import { Card } from "../../components/Card";
import { RiskBadge } from "../../components/RiskBadge";
import { LoadingState, ErrorState } from "../../components/States";
import { getAuditTrail } from "../../api/admin";
import { extractErrorMessage } from "../../api/client";

const NAV_ITEMS = [
  { to: "/admin", label: "Overview", icon: <LayoutDashboard size={16} /> },
  { to: "/admin/users", label: "Users", icon: <Users size={16} /> },
  { to: "/admin/courses", label: "Courses", icon: <BookOpen size={16} /> },
  { to: "/admin/audit", label: "Audit Trail", icon: <ClipboardList size={16} /> },
];

const PAGE_SIZE = 15;

export default function AuditTrailPage() {
  const [search, setSearch] = useState("");
  const [page, setPage] = useState(1);

  const { data, isLoading, error } = useQuery({
    queryKey: ["audit-trail"],
    queryFn: () => getAuditTrail(),
  });

  const filtered = useMemo(() => {
    if (!data) return [];
    const term = search.trim().toLowerCase();
    if (!term) return data;
    return data.filter(
      (e) =>
        e.studentName.toLowerCase().includes(term) ||
        e.registrationNo.toLowerCase().includes(term) ||
        e.courseCode?.toLowerCase().includes(term)
    );
  }, [data, search]);

  const totalPages = Math.max(1, Math.ceil(filtered.length / PAGE_SIZE));
  const currentPage = Math.min(page, totalPages);
  const pageItems = filtered.slice((currentPage - 1) * PAGE_SIZE, currentPage * PAGE_SIZE);

  function updateSearch(value: string) {
    setSearch(value);
    setPage(1);
  }

  return (
    <Layout navItems={NAV_ITEMS}>
      <div className="mx-auto max-w-5xl space-y-6">
        <div className="flex flex-col gap-4 sm:flex-row sm:items-end sm:justify-between">
          <div>
            <h1 className="text-xl font-semibold text-neutral-900 dark:text-neutral-100">
              Prediction &amp; Recommendation Audit Trail
            </h1>
            <p className="mt-1 text-sm text-neutral-500 dark:text-neutral-400">
              Every prediction generated by the system, most recent first -- supports the transparency
              requirement so predictions and recommendations can always be traced back.
            </p>
          </div>
          <div className="relative shrink-0">
            <Search className="absolute left-3 top-2.5 text-neutral-400 dark:text-neutral-500" size={14} />
            <input
              type="text"
              placeholder="Search student, reg no, or course..."
              value={search}
              onChange={(e) => updateSearch(e.target.value)}
              className="w-64 rounded-xl border border-neutral-300 bg-white py-2 pl-8 pr-3 text-sm outline-none focus:border-blue-500 focus:ring-2 focus:ring-blue-500/20 dark:border-neutral-800 dark:bg-neutral-900 dark:text-neutral-100"
            />
          </div>
        </div>

        {isLoading && <LoadingState label="Loading audit trail..." />}
        {error && <ErrorState message={extractErrorMessage(error)} />}

        {data && (
          <Card>
            <div className="divide-y divide-neutral-100 dark:divide-neutral-800/60">
              {pageItems.map((entry) => (
                <div key={entry.predictionId} className="py-3">
                  <div className="flex flex-wrap items-center justify-between gap-2">
                    <div>
                      <span className="font-medium text-neutral-900 dark:text-neutral-100">
                        {entry.studentName}
                      </span>
                      <span className="ml-2 text-xs text-neutral-500 dark:text-neutral-400">
                        {entry.registrationNo} · {entry.courseCode} · {entry.semester}
                      </span>
                    </div>
                    <div className="flex items-center gap-2">
                      <RiskBadge level={entry.riskLevel} size="sm" />
                      <span className="text-xs text-neutral-400 dark:text-neutral-500">
                        {entry.modelUsed} · {new Date(entry.generatedAt).toLocaleString()}
                      </span>
                    </div>
                  </div>
                  {entry.recommendationMessages.length > 0 && (
                    <ul className="mt-2 list-inside list-disc text-xs text-neutral-500 dark:text-neutral-400">
                      {entry.recommendationMessages.map((m, i) => (
                        <li key={i}>{m}</li>
                      ))}
                    </ul>
                  )}
                </div>
              ))}
              {pageItems.length === 0 && (
                <p className="py-6 text-center text-sm text-neutral-500 dark:text-neutral-400">
                  {data.length === 0 ? "No predictions generated yet." : "No entries match your search."}
                </p>
              )}
            </div>

            {filtered.length > 0 && (
              <div className="flex items-center justify-between pt-4 text-xs font-semibold text-neutral-500 dark:text-neutral-400">
                <span>
                  Showing {(currentPage - 1) * PAGE_SIZE + 1}-{Math.min(currentPage * PAGE_SIZE, filtered.length)} of {filtered.length}
                </span>
                <div className="flex items-center gap-2">
                  <button
                    onClick={() => setPage((p) => Math.max(1, p - 1))}
                    disabled={currentPage === 1}
                    className="flex items-center gap-1 rounded-lg border border-neutral-300 px-2.5 py-1.5 hover:bg-neutral-50 disabled:opacity-40 disabled:cursor-not-allowed dark:border-neutral-800 dark:hover:bg-neutral-800/80 cursor-pointer"
                  >
                    <ChevronLeft size={13} /> Prev
                  </button>
                  <span>Page {currentPage} of {totalPages}</span>
                  <button
                    onClick={() => setPage((p) => Math.min(totalPages, p + 1))}
                    disabled={currentPage === totalPages}
                    className="flex items-center gap-1 rounded-lg border border-neutral-300 px-2.5 py-1.5 hover:bg-neutral-50 disabled:opacity-40 disabled:cursor-not-allowed dark:border-neutral-800 dark:hover:bg-neutral-800/80 cursor-pointer"
                  >
                    Next <ChevronRight size={13} />
                  </button>
                </div>
              </div>
            )}
          </Card>
        )}
      </div>
    </Layout>
  );
}
